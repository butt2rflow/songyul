export const LANGUAGE_KEY = "pg-language";

export function pickLanguage(saved, browserLanguage) {
  if (saved === "ko" || saved === "en") return saved;
  return /^ko/i.test(browserLanguage || "") ? "ko" : "en";
}

export const speechLocale = (language) => language === "ko" ? "ko-KR" : "en-US";

export function text(key, language, ...args) {
  return strings[key][language === "ko" ? 0 : 1].replace(/\{(\d+)\}/g, (_, i) => args[i]);
}
